export function getWaveDef(waveNum: number): WaveDef {
  if (waveNum <= 20) {
    return WAVES[Math.max(0, waveNum - 1)];
  }
  // Endless mode scaling (Wave 21+)
  const extra = waveNum - 20;
  const hpMult = +(20.0 * Math.pow(1.24, extra)).toFixed(2);
  const dmgMult = +(3.6 * Math.pow(1.1, extra)).toFixed(2);
  const hasBoss = waveNum % 5 === 0;
  const bossPool: EnemyKind[] = [
    'boss_skeleton_king',
    'boss_abyss_lord',
    'boss_frost_wyrm',
    'boss_doom_overlord',
  ];
  return {
    wave: waveNum,
    title: hasBoss ? `【无尽第 ${waveNum} 波 · 魔神再临】` : `无尽狂潮 · 第 ${waveNum} 波`,
    lanes: 3,
    groups: [
      { kind: 'doom_guard', count: 24 + Math.min(36, extra * 2) },
      { kind: 'infernal_titan', count: 12 + Math.min(20, extra) },
      { kind: 'thunder_mage', count: 18 + Math.min(24, extra) },
    ],
    boss: hasBoss ? bossPool[Math.floor((waveNum / 5) % bossPool.length)] : undefined,
    hpMult,
    dmgMult,
    prepSeconds: 14,
  };
}
